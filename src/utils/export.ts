import type { AnimationDocument } from '@/types'
import { generateCss } from './css'

export function exportCss(doc: AnimationDocument): string {
  return [
    `/* Generated by Keyforge */`,
    `/* Animation: ${doc.name} | Duration: ${doc.duration}ms */`,
    '',
    generateCss(doc)
      .replace(/animation-play-state: var\(--play-state, paused\);\n/g, ''),
  ].join('\n')
}
